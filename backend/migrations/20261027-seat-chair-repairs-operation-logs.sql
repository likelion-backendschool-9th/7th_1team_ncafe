-- Apply before deploying to a database that uses ddl-auto=validate/none.
CREATE TABLE IF NOT EXISTS seat_chair_repairs (
    seat_id BIGINT NOT NULL REFERENCES seats(id) ON DELETE CASCADE,
    chair_no INTEGER NOT NULL CHECK (chair_no > 0),
    CONSTRAINT uq_seat_chair_repairs UNIQUE (seat_id, chair_no)
);

-- Snapshot identifiers deliberately survive later member/branch removal.
CREATE TABLE IF NOT EXISTS branch_operation_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id VARCHAR(255) NOT NULL,
    actor_no BIGINT NOT NULL,
    actor_login_id VARCHAR(255) NOT NULL,
    action VARCHAR(40) NOT NULL,
    target VARCHAR(100) NOT NULL,
    before_value VARCHAR(100) NOT NULL,
    after_value VARCHAR(100) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_branch_operation_logs_branch_time
    ON branch_operation_logs (branch_id, occurred_at, id);
